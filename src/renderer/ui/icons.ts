const DEFAULT_SIZE = 16;

export function icon(name: string, size = DEFAULT_SIZE): HTMLSpanElement {
  const span = document.createElement('span');
  span.className = `icon icon-${name}`;
  span.innerHTML = `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICON_PATHS[name] || ''}</svg>`;
  return span;
}

export function iconButton(name: string, title: string, onClick: (e: MouseEvent) => void, extraClass = ''): HTMLButtonElement {
  return h('button', { class: `icon-btn ${extraClass}`, title, 'aria-label': title, type: 'button', onclick: onClick }, icon(name));
}

const SHORT_METHODS: Record<string, string> = { DELETE: 'DEL', OPTIONS: 'OPT' };

export function methodBadge(method: string | undefined, small = false): HTMLSpanElement {
  const m = String(method || 'GET').toUpperCase();
  return h('span', { class: `method method-${m.toLowerCase()}${small ? ' small' : ''}` }, small ? (SHORT_METHODS[m] || m) : m);
}
